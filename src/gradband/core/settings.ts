export function 默认设置(): Settings {
  return {
    开关: { 自动结算: true, 状态栏标记: true },
    频率: { 数据AI: 1 },
    api: { 数据AI: { mode: 'tavern' }, 法术AI: { mode: 'tavern' } },
    提示词: 默认提示词(),
  };
}

let cache: Settings | null = null;

export function loadSettings(): Settings {
  if (cache) return cache;
  const def = 默认设置();
  const raw = readExtensionSettings<Partial<Settings>>(SETTINGS_KEY, {});
  cache = {
    // 白名单取键：旧档可能残留**已废弃的开关键**（如 pre-v1.7.0 的「情感分析」，感情AI 删除后无人读取），
    // 而面板是按 Object.keys(s.开关) 动态渲染的——残留键会变成一个点了没用的幽灵勾选框。
    // 这里只认已知键，顺带在下次保存时把残留键从 extensionSettings 里清掉。
    开关: {
      自动结算: typeof raw.开关?.自动结算 === 'boolean' ? raw.开关.自动结算 : def.开关.自动结算,
      状态栏标记: typeof raw.开关?.状态栏标记 === 'boolean' ? raw.开关.状态栏标记 : def.开关.状态栏标记,
    },
    频率: { 数据AI: (raw.频率 && typeof raw.频率.数据AI === 'number' ? raw.频率.数据AI : def.频率.数据AI) },
    api: {
      数据AI: raw.api?.数据AI ?? def.api.数据AI,
      法术AI: raw.api?.法术AI ?? def.api.法术AI,
    },
    // v1.8.7 拆分迁移：新键缺失时回退旧合并键 法术AI（保住用户自定义过的双场景提示词，
    // 两个新位先都沿用旧内容，用户在提示词页分别编辑保存后即各自独立）；
    // 旧键也没有（全新安装）→ 各用新默认。下次 saveSettings 全量写回后旧键自然消失。
    // 旧键已不在 Settings 类型里，用宽松转型读取旧档。
    提示词: ((): Settings['提示词'] => {
      const p = (raw.提示词 ?? {}) as (Partial<Settings['提示词']> & { 法术AI?: PromptSegment[] }) | undefined;
      return {
        数据AI: p?.数据AI ?? def.提示词.数据AI,
        法术AI自创: p?.法术AI自创 ?? p?.法术AI ?? def.提示词.法术AI自创,
        法术AI剧情: p?.法术AI剧情 ?? p?.法术AI ?? def.提示词.法术AI剧情,
      };
    })(),   // 感情AI 相关键已全删（旧档残留不读取）
    窗口: raw.窗口,
    悬浮球: raw.悬浮球,
  };
  return cache;
}

export function saveSettings(s: Settings): void {
  cache = s;
  writeExtensionSettings(SETTINGS_KEY, s);
}

export function resetSettingsCache(): void { cache = null; }
